import { type Cell, createGrid, type Grid, nextGeneration, population, setCells } from "../life";
import { DEFAULT_SPEED, MAX_SPEED, MIN_SPEED } from "./settings";

// Population isn't stored here: it's derived from the grid.
export interface SimulationState {
  readonly grid: Grid;
  readonly generation: number;
  readonly running: boolean;
  readonly speed: number;
  readonly label: BoardLabel;
}

// What's on the board, for display.
export interface BoardLabel {
  readonly name: string;
  readonly note: string;
}

export const EMPTY_LABEL: BoardLabel = {
  name: "Empty",
  note: "Draw on the grid or pick a pattern.",
};

export const DRAWN_LABEL: BoardLabel = {
  name: "Custom",
  note: "Drawn by hand.",
};

// Random boards are generated by the caller and passed in with "load", which
// keeps this reducer deterministic.
export type SimulationAction =
  | { type: "step" }
  | { type: "play" }
  | { type: "pause" }
  | { type: "togglePlay" }
  | { type: "setSpeed"; speed: number }
  | { type: "paint"; cells: readonly Cell[]; alive: boolean }
  | { type: "clear" }
  | { type: "load"; grid: Grid; label: BoardLabel };

export function createInitialState(grid: Grid, label: BoardLabel = EMPTY_LABEL): SimulationState {
  return { grid, generation: 0, running: false, speed: DEFAULT_SPEED, label };
}

export function simulationReducer(
  state: SimulationState,
  action: SimulationAction,
): SimulationState {
  switch (action.type) {
    case "step": {
      const grid = nextGeneration(state.grid);
      // nothing can be born on an empty board, so stop
      const extinct = population(grid) === 0;
      return {
        ...state,
        grid,
        generation: state.generation + 1,
        running: state.running && !extinct,
      };
    }

    case "play":
      return startIfPossible(state);

    case "pause":
      return state.running ? { ...state, running: false } : state;

    case "togglePlay":
      return state.running ? { ...state, running: false } : startIfPossible(state);

    case "setSpeed":
      return { ...state, speed: clampSpeed(action.speed) };

    case "paint": {
      const grid = setCells(state.grid, action.cells, action.alive);
      if (grid === state.grid) return state;
      return { ...state, grid, label: DRAWN_LABEL };
    }

    case "clear":
      return {
        ...state,
        grid: createGrid(state.grid.width, state.grid.height),
        generation: 0,
        running: false,
        label: EMPTY_LABEL,
      };

    case "load":
      return { ...state, grid: action.grid, generation: 0, running: false, label: action.label };
  }
}

function startIfPossible(state: SimulationState): SimulationState {
  if (state.running || population(state.grid) === 0) return state;
  return { ...state, running: true };
}

export function clampSpeed(speed: number): number {
  if (Number.isNaN(speed)) return DEFAULT_SPEED;
  return Math.min(MAX_SPEED, Math.max(MIN_SPEED, Math.round(speed)));
}
